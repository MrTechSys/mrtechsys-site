/**
 * Generic DB interface that can be backed by Cloudflare D1, KV, or an external API.
 * For now, this is a conceptual wrapper that the user can wire to their actual storage.
 */

export interface DBEntity<T> {
  list(options?: any): Promise<T[]>;
  get(id: string): Promise<T | null>;
  create(data: Omit<T, 'id' | 'created_at' | 'updated_at'>): Promise<T>;
  update(id: string, data: Partial<T>): Promise<T>;
  delete(id: string): Promise<void>;
  filter(query: any, order?: string, limit?: number): Promise<T[]>;
}

